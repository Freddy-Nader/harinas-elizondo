/**
 * RF-02 · UC-01. Pure rules for lab equipment. No database here, so it is unit tested.
 */

export type EquipmentStatus = "active" | "inactive" | "retired";

export const EQUIPMENT_STATUS_LABEL: Record<EquipmentStatus, string> = {
  active: "Activo",
  inactive: "Inactivo",
  retired: "Baja",
};

// 31 symbols without look-alikes (no 0, 1, I, L, O)
const KEY_ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789";
export const EQUIPMENT_KEY_LENGTH = 8;
// Largest multiple of 31 below 256. Bytes at or above it are dropped so every symbol is equally likely
const BYTE_LIMIT = 256 - (256 % KEY_ALPHABET.length);

/**
 * BR-EQP-01. Random 8-character key generated by the app. Uniqueness is enforced by the
 * primary key, and the action retries on the rare collision.
 */
export function generateEquipmentKey(
  randomBytes: (n: number) => Uint8Array = (n) => crypto.getRandomValues(new Uint8Array(n)),
): string {
  let key = "";
  while (key.length < EQUIPMENT_KEY_LENGTH) {
    for (const byte of randomBytes(EQUIPMENT_KEY_LENGTH)) {
      if (byte >= BYTE_LIMIT) continue;
      key += KEY_ALPHABET[byte % KEY_ALPHABET.length];
      if (key.length === EQUIPMENT_KEY_LENGTH) break;
    }
  }
  return key;
}

export function isEquipmentKey(value: string): boolean {
  return /^[A-HJ-KM-NP-Z2-9]{8}$/.test(value);
}

const optionalText = (max: number, label: string) =>
  z
    .string()
    .trim()
    .max(max, `${label} admite máximo ${max} caracteres.`)
    .transform((v) => v || null);

const optionalDate = z
  .string()
  .trim()
  .refine((v) => !v || z.iso.date().safeParse(v).success, "La fecha no es válida.")
  .transform((v) => v || null);

/** RF-02. Fields captured in the equipment form. The type is fixed once the equipment exists. */
export const equipmentInputSchema = z
  .object({
    shortDescription: z
      .string()
      .trim()
      .min(1, "La descripción corta es obligatoria.")
      .max(60, "La descripción corta admite máximo 60 caracteres."),
    longDescription: optionalText(1000, "La descripción larga"),
    brand: optionalText(40, "La marca"),
    model: optionalText(40, "El modelo"),
    serialNumber: optionalText(30, "El número de serie"),
    supplier: optionalText(80, "El proveedor"),
    acquiredOn: optionalDate,
    warrantyUntil: optionalDate,
    location: optionalText(80, "La ubicación"),
    responsible: optionalText(100, "El responsable"),
  })
  .refine((v) => !v.acquiredOn || !v.warrantyUntil || v.warrantyUntil >= v.acquiredOn, {
    path: ["warrantyUntil"],
    message: "La garantía no puede terminar antes de la fecha de adquisición.",
  });

export const equipmentTypeSchema = z.enum(["alveograph", "farinograph"], {
  error: "Elige el tipo de equipo.",
});

export type EquipmentInput = z.output<typeof equipmentInputSchema>;

/** RF-02. International limits captured per parameter. Inclusive range. */
export const limitSchema = z
  .object({
    lowerLimit: z.number({ error: "Captura el límite inferior." }).finite(),
    upperLimit: z.number({ error: "Captura el límite superior." }).finite(),
  })
  .refine((v) => v.lowerLimit <= v.upperLimit, {
    path: ["upperLimit"],
    message: "El límite inferior no puede ser mayor que el superior.",
  });

/** Status changes allowed by D-16. `retired` (baja) is final. */
export type StatusChange = "deactivate" | "reactivate" | "retire";

const TRANSITIONS: Record<StatusChange, { from: EquipmentStatus[]; to: EquipmentStatus }> = {
  deactivate: { from: ["active"], to: "inactive" },
  reactivate: { from: ["inactive"], to: "active" },
  retire: { from: ["active", "inactive"], to: "retired" },
};

/** D-16. Target status for a change, or an error message when the change is not allowed. */
export function applyStatusChange(
  current: EquipmentStatus,
  change: StatusChange,
  reason: string,
): { ok: true; status: EquipmentStatus; reason: string | null } | { ok: false; error: string } {
  const rule = TRANSITIONS[change];
  if (!rule.from.includes(current)) {
    return current === "retired"
      ? { ok: false, error: "El equipo está dado de baja y ya no se puede modificar." }
      : { ok: false, error: "Ese cambio de estado no aplica al estado actual del equipo." };
  }
  const trimmed = reason.trim();
  if (change !== "reactivate" && !trimmed) {
    return { ok: false, error: "Escribe el motivo del cambio de estado." };
  }
  if (trimmed.length > 200) return { ok: false, error: "El motivo admite máximo 200 caracteres." };
  return { ok: true, status: rule.to, reason: change === "reactivate" ? null : trimmed };
}

/** Only active and inactive equipment can be edited. Retired is history only. */
export function isEditable(status: EquipmentStatus) {
  return status !== "retired";
}

export type Readiness =
  | { usable: true }
  | { usable: false; reason: "status"; status: EquipmentStatus }
  | { usable: false; reason: "limits"; missing: string[] };

/**
 * BR-EQP-03. Equipment can be used for certification only when it is active and every
 * parameter it measures has international reference values.
 */
export function equipmentReadiness(
  type: EquipmentType,
  status: EquipmentStatus,
  limits: LimitsByParameter,
): Readiness {
  if (status !== "active") return { usable: false, reason: "status", status };
  const missing = missingReferenceValues(
    parametersFor(type).map((p) => p.code),
    limits,
  );
  return missing.length ? { usable: false, reason: "limits", missing } : { usable: true };
}

/** Change history detail: only the fields that changed, as { field: [before, after] }. */
export function changedFields<T extends Record<string, unknown>>(before: T, after: Partial<T>) {
  const diff: Record<string, [unknown, unknown]> = {};
  for (const key of Object.keys(after)) {
    const a = before[key] ?? null;
    const b = after[key] ?? null;
    if (a !== b) diff[key] = [a, b];
  }
  return diff;
}

